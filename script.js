// Toggle Audio
function toggleMusic() {
    const audio = document.getElementById("bgMusic");
    const icon = document.getElementById("musicIcon");
    if (!audio || !icon) return;

    if (audio.paused) {
        audio.play().then(() => {
            icon.textContent = "🎶";
        }).catch(err => console.log("Autoplay ditolak oleh browser:", err));
    } else {
        audio.pause();
        icon.textContent = "🎵";
    }
}

