// Toggle Audio
let isPlaying = false;
function toggleMusic() {
    const audio = document.getElementById("bgMusic");
    const icon = document.getElementById("musicIcon");

    if (isPlaying) {
        audio.pause();
        icon.textContent = "🎵";
    } else {
        audio.play();
        icon.textContent = "🎶";
    }
    isPlaying = !isPlaying;
}

